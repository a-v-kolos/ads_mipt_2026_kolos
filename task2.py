# Пример
# Входные данные 
# 2
# 1 100
# 10
# 1 2
# 2 1
# 3 1
# 4 1
# 5 1
# 6 1
# 7 1
# 8 1
# 9 1
# 10 1
# 4
# 1 2
# 1 10
# 2 4 1 1000
# 1 10

# Результат
# 1 10
# 1 10 9 8 7 6 5 4 3 2
# 4 1 10 9 8 7 6 5 3 2


# считываем количество критериев n
n = int(input())

# считываем список коэффициентов a[0..n-1], по которым считается взвешенная сумма документа
a = list(map(int, input().split()))

# считываем количество документов d
d = int(input())

# список исходных векторов документов (значения признаков каждого документа)
docs = []

# список кортежей для сортировки: ((-score, idx), score, idx, doc)
# -score - ключ для сортировки по убыванию score (больше score => меньше -score => раньше в списке)
# idx - индекс документа (нужен для уникальности ключа и стабильного порядка при равных score)
# score - сам вес (взвешенная сумма)
# doc - ссылка на исходный вектор документа
items = []

# pos[i] - текущая позиция документа с индексом i в отсортированном списке items
pos = [0] * d

# считываем все документы и сразу считаем их score
for i in range(d):
    doc = list(map(int, input().split()))  # вектор документа
    docs.append(doc)

    # считаем взвешенную сумму score = Σ a[j] * doc[j]
    s = 0
    for j in range(n):
        s += a[j] * doc[j]

    # добавляем в items кортеж: ключ (-s, i), score s, индекс i, сам документ
    items.append(((-s, i), s, i, doc))

# сортируем по ключу (-score, idx) - по убыванию score, при равенстве - по возрастанию idx
items.sort(key=lambda x: x[0])

# заполнение массива позиций (для каждого документа его индекс в отсортированном items)
for t in range(d):
    pos[items[t][2]] = t

# считываем количество запросов q
q = int(input())

out = []  # накапливаем ответы на запросы типа 1

# выполнение запроса
for _ in range(q):
    z = list(map(int, input().split()))  # читаем запрос

    if z[0] == 1:
        # Запрос типа 1: вывести первые k документов в порядке рейтинга
        k = z[1]
        # выводим индексы первых k элементов items(items[t][2] — 0-based, +1 — 1-based)
        out.append(" ".join(str(items[t][2] + 1) for t in range(k)))

    else:
        # Запрос типа 2: изменить j-й признак i-го документа на значение v
        i_doc = z[1] - 1   # индекс документа (0-based)
        j = z[2] - 1       # индекс признака (0-based)
        v = z[3]           # новое значение

        doc = docs[i_doc]              # ссылка на вектор документа
        delta = a[j] * (v - doc[j])    # на сколько изменится score
        doc[j] = v                     # обновляем признак в исходном документе

        p = pos[i_doc]                 # текущая позиция документа в items
        old_score = items[p][1]        # старый score
        new_score = old_score + delta  # новый score

        # удаление документа из отсортированного списка
        items.pop(p)

        # подготовка нового ключа для вставки: (-new_score, i_doc)
        new_key = (-new_score, i_doc)

        # Бинарный поиск места вставки в отсортированном по ключу списке
        lo, hi = 0, len(items)
        while lo < hi:
            mid = (lo + hi) // 2
            if items[mid][0] < new_key:
                lo = mid + 1
            else:
                hi = mid
        idx = lo

        # вставка документа на найденное место
        items.insert(idx, (new_key, new_score, i_doc, doc))

        # обновление pos для всех элементов, чья позиция сдвинулась
        if p < idx:
            # Документ сдвинулся вправо (вниз по рейтингу):
            # элементы с p до idx сдвинулись на одну позицию влево
            for t in range(p, idx + 1):
                pos[items[t][2]] = t
        else:
            # Документ сдвинулся влево (вверх по рейтингу):
            # элементы с idx до p сдвинулись на одну позицию вправо
            for t in range(idx, p + 1):
                pos[items[t][2]] = t

# Выводим все ответы на запросы типа 1, каждый с новой строки
print("\n".join(out))
